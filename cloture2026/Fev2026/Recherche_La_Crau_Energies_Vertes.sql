-- Base de données : Oracle EBS Production
--
-- OBJECTIF : Extraire toutes les informations du fournisseur "LA CRAU ENERGIES VERTES"
-- incluant les Operating Units, sites, responsabilités, factures, etc.
-- =====================================================================

-- =====================================================================
-- PARTIE 1 : Informations générales du fournisseur
-- =====================================================================
SELECT 
    -- Identification
    APS.VENDOR_ID,
    APS.VENDOR_NAME,
    APS.VENDOR_NAME_ALT,
    APS.SEGMENT1 AS NUMERO_FOURNISSEUR,
    APS.VENDOR_TYPE_LOOKUP_CODE AS TYPE_FOURNISSEUR,
    
    -- Statut
    APS.ENABLED_FLAG AS ACTIF,
    APS.HOLD_FLAG AS EN_ATTENTE,
    APS.HOLD_REASON AS RAISON_ATTENTE,
    APS.HOLD_BY AS MIS_EN_ATTENTE_PAR,
    APS.HOLD_DATE AS DATE_MISE_ATTENTE,
    
    -- Dates
    APS.START_DATE_ACTIVE AS DATE_DEBUT_VALIDITE,
    APS.END_DATE_ACTIVE AS DATE_FIN_VALIDITE,
    APS.CREATION_DATE AS DATE_CREATION,
    APS.LAST_UPDATE_DATE AS DERNIERE_MODIFICATION,
    
    -- Organisation
    APS.ORGANIZATION_TYPE_LOOKUP_CODE AS TYPE_ORGANISATION,
    APS.CUSTOMER_NUM AS NUMERO_CLIENT,
    APS.ONE_TIME_FLAG AS FOURNISSEUR_PONCTUEL,
    
    -- Informations fiscales et monétaires
    APS.PURCHASING_HOLD_REASON AS RAISON_BLOCAGE_ACHAT,
    APS.INVOICE_CURRENCY_CODE AS DEVISE_FACTURE_DEFAUT,
    APS.PAYMENT_CURRENCY_CODE AS DEVISE_PAIEMENT_DEFAUT,
    APS.VAT_REGISTRATION_NUM AS NUMERO_TVA,
    APS.NUM_1099 AS NUMERO_FISCAL,
    
    -- Audit
    APS.CREATED_BY AS CREE_PAR,
    APS.LAST_UPDATED_BY AS MODIFIE_PAR
FROM 
    AP.AP_SUPPLIERS APS
WHERE 
    UPPER(APS.VENDOR_NAME) LIKE '%LA CRAU ENERGIES VERTES%'
ORDER BY 
    APS.VENDOR_NAME;

-- =====================================================================
-- PARTIE 2 : Sites du fournisseur avec Operating Units et termes de paiement
-- =====================================================================
SELECT 
    -- Identification fournisseur
    APS.VENDOR_NAME,
    APS.SEGMENT1 AS NUMERO_FOURNISSEUR,
    APS.VENDOR_ID,
    
    -- Identification site
    APSA.VENDOR_SITE_ID,
    APSA.VENDOR_SITE_CODE AS CODE_SITE,
    APSA.VENDOR_SITE_CODE_ALT AS CODE_SITE_ALTERNATIF,
    
    -- *** OPERATING UNIT ***
    APSA.ORG_ID,
    HOU.NAME AS OPERATING_UNIT,
    HOU.SHORT_CODE AS CODE_OU,
    
    -- Adresse
    APSA.ADDRESS_LINE1 AS ADRESSE_1,
    APSA.ADDRESS_LINE2 AS ADRESSE_2,
    APSA.ADDRESS_LINE3 AS ADRESSE_3,
    APSA.CITY AS VILLE,
    APSA.STATE AS REGION,
    APSA.ZIP AS CODE_POSTAL,
    APSA.COUNTRY AS PAYS,
    
    -- Contact
    APSA.PHONE AS TELEPHONE,
    APSA.FAX AS FAX,
    APSA.EMAIL_ADDRESS AS EMAIL,
    
    -- Statut site
    APSA.INACTIVE_DATE AS DATE_INACTIVATION,
    APSA.HOLD_ALL_PAYMENTS_FLAG AS BLOCAGE_TOUS_PAIEMENTS,
    APSA.HOLD_FUTURE_PAYMENTS_FLAG AS BLOCAGE_PAIEMENTS_FUTURS,
    APSA.HOLD_REASON AS RAISON_BLOCAGE,
    
    -- Termes de paiement
    APSA.TERMS_ID,
    APT.NAME AS NOM_TERME_PAIEMENT,
    APT.DESCRIPTION AS DESCRIPTION_TERME,
    APT.DUE_DAYS AS JOURS_ECHEANCE,
    APT.DISCOUNT_DAYS AS JOURS_ESCOMPTE,
    APT.DISCOUNT_PERCENT AS POURCENTAGE_ESCOMPTE,
    APT.ENABLED_FLAG AS TERME_ACTIF,
    
    -- Options de paiement
    APSA.PAYMENT_METHOD_LOOKUP_CODE AS METHODE_PAIEMENT,
    APSA.PAYMENT_PRIORITY AS PRIORITE_PAIEMENT,
    APSA.PAY_GROUP_LOOKUP_CODE AS GROUPE_PAIEMENT,
    APSA.ALWAYS_TAKE_DISC_FLAG AS TOUJOURS_APPLIQUER_ESCOMPTE,
    APSA.EXCLUDE_FREIGHT_FROM_DISCOUNT AS EXCLURE_FRAIS_PORT_ESCOMPTE,
    
    -- Options fiscales
    APSA.VAT_CODE AS CODE_TVA,
    APSA.ALLOW_AWT_FLAG AS AUTORISER_RETENUE_SOURCE,
    APSA.AWT_GROUP_ID AS GROUPE_RETENUE_SOURCE,
    
    -- Options comptables
    APSA.ACCTS_PAY_CODE_COMBINATION_ID AS COMPTE_FOURNISSEUR,
    GCC1.CONCATENATED_SEGMENTS AS CODE_COMPTABLE_FOURNISSEUR,
    APSA.PREPAY_CODE_COMBINATION_ID AS COMPTE_AVANCE,
    GCC2.CONCATENATED_SEGMENTS AS CODE_COMPTABLE_AVANCE,
    
    -- Options achats et factures
    APSA.PURCHASING_SITE_FLAG AS SITE_ACHATS,
    APSA.PAY_SITE_FLAG AS SITE_PAIEMENT,
    APSA.RFQ_ONLY_SITE_FLAG AS SITE_APPEL_OFFRES_UNIQUEMENT,
    APSA.INVOICE_AMOUNT_LIMIT AS LIMITE_MONTANT_FACTURE,
    APSA.MATCH_OPTION AS OPTION_RAPPROCHEMENT,
    APSA.CREATE_DEBIT_MEMO_FLAG AS CREER_AVOIR,
    
    -- Dates
    APSA.CREATION_DATE AS DATE_CREATION_SITE,
    APSA.LAST_UPDATE_DATE AS DERNIERE_MODIFICATION_SITE,
    
    -- Audit
    APSA.CREATED_BY AS SITE_CREE_PAR,
    APSA.LAST_UPDATED_BY AS SITE_MODIFIE_PAR
    
FROM 
    AP.AP_SUPPLIERS APS
    INNER JOIN AP.AP_SUPPLIER_SITES_ALL APSA 
        ON APS.VENDOR_ID = APSA.VENDOR_ID
    LEFT OUTER JOIN HR.HR_OPERATING_UNITS HOU 
        ON APSA.ORG_ID = HOU.ORGANIZATION_ID
    LEFT OUTER JOIN AP.AP_TERMS APT 
        ON APSA.TERMS_ID = APT.TERM_ID
    LEFT OUTER JOIN GL.GL_CODE_COMBINATIONS_KFV GCC1
        ON APSA.ACCTS_PAY_CODE_COMBINATION_ID = GCC1.CODE_COMBINATION_ID
    LEFT OUTER JOIN GL.GL_CODE_COMBINATIONS_KFV GCC2
        ON APSA.PREPAY_CODE_COMBINATION_ID = GCC2.CODE_COMBINATION_ID
WHERE 
    UPPER(APS.VENDOR_NAME) LIKE '%LA CRAU ENERGIES VERTES%'
ORDER BY 
    APS.VENDOR_NAME, 
    HOU.NAME,
    APSA.VENDOR_SITE_CODE;

