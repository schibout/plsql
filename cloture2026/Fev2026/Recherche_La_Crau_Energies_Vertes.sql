-- =====================================================================
-- PARTIE 4 : Comptes bancaires du fournisseur
-- =====================================================================
SELECT 
    APS.VENDOR_NAME,
    APS.SEGMENT1 AS NUMERO_FOURNISSEUR,
    IEBA.EXT_BANK_ACCOUNT_ID,
    IEBA.BANK_ACCOUNT_NAME AS NOM_COMPTE,
    IEBA.BANK_ACCOUNT_NUM AS NUMERO_COMPTE,
    IEBA.BANK_ACCOUNT_TYPE AS TYPE_COMPTE,
    IEBA.IBAN AS IBAN,
    IEBA.CHECK_DIGITS AS CLE_RIB,
    IEBA.CURRENCY_CODE AS DEVISE,
    IEBA.ACCOUNT_SUFFIX AS SUFFIXE_COMPTE,
    IEBA.DESCRIPTION AS DESCRIPTION,
    IEBA.COUNTRY_CODE AS CODE_PAYS,
    IEBA.BRANCH_ID,
    IEBB.BRANCH_NAME AS NOM_AGENCE,
    IEBB.BRANCH_NUMBER AS NUMERO_AGENCE,
    IEBB.BIC AS CODE_BIC_SWIFT,
    IEBB.BANK_NAME AS NOM_BANQUE,
    IEBB.BANK_NUMBER AS NUMERO_BANQUE,
    IEBA.START_DATE AS DATE_DEBUT_VALIDITE,
    IEBA.END_DATE AS DATE_FIN_VALIDITE,
    IEBA.CREATION_DATE AS DATE_CREATION,
    IEBA.LAST_UPDATE_DATE AS DERNIERE_MODIFICATION
FROM 
    AP.AP_SUPPLIERS APS
    INNER JOIN IBY.IBY_EXTERNAL_PAYEES_ALL IEPA 
        ON APS.VENDOR_ID = IEPA.PAYEE_PARTY_ID 
        AND IEPA.PAYMENT_FUNCTION = 'PAYABLES_DISB'
        AND IEPA.PARTY_SITE_ID IS NULL
    INNER JOIN IBY.IBY_PMT_INSTR_USES_ALL IPIA 
        ON IEPA.EXT_PAYEE_ID = IPIA.EXT_PMT_PARTY_ID
    INNER JOIN IBY.IBY_EXT_BANK_ACCOUNTS IEBA 
        ON IPIA.INSTRUMENT_ID = IEBA.EXT_BANK_ACCOUNT_ID
    LEFT OUTER JOIN CE.CE_BANK_BRANCHES_V IEBB 
        ON IEBA.BRANCH_ID = IEBB.BRANCH_PARTY_ID
WHERE 
    UPPER(APS.VENDOR_NAME) LIKE '%LA CRAU ENERGIES VERTES%'
    AND (IEBA.END_DATE IS NULL OR IEBA.END_DATE > SYSDATE)
ORDER BY 
    APS.VENDOR_NAME, 
    IEBA.BANK_ACCOUNT_NAME;

-- =====================================================================
-- PARTIE 5 : Factures du fournisseur (2025-2026)
-- =====================================================================
SELECT 
    APS.VENDOR_NAME,
    APS.SEGMENT1 AS NUMERO_FOURNISSEUR,
    HOU.NAME AS OPERATING_UNIT,
    AIA.INVOICE_ID,
    AIA.INVOICE_NUM AS NUMERO_FACTURE,
    AIA.INVOICE_DATE AS DATE_FACTURE,
    AIA.INVOICE_AMOUNT AS MONTANT_FACTURE,
    AIA.INVOICE_CURRENCY_CODE AS DEVISE,
    AIA.GL_DATE AS DATE_COMPTABLE,
    AIA.PAYMENT_STATUS_FLAG AS STATUT_PAIEMENT,
    DECODE(AIA.PAYMENT_STATUS_FLAG, 
        'N', 'IMPAYÉE', 
        'P', 'PARTIELLEMENT PAYÉE', 
        'Y', 'PAYÉE') AS STATUT_PAIEMENT_LIBELLE,
    AIA.AMOUNT_PAID AS MONTANT_PAYE,
    AIA.CANCELLED_DATE AS DATE_ANNULATION,
    AIA.CREATION_DATE AS DATE_CREATION,
    AIA.LAST_UPDATE_DATE AS DERNIERE_MODIFICATION,
    APSA.VENDOR_SITE_CODE AS SITE_FOURNISSEUR,
    AIA.DESCRIPTION AS DESCRIPTION_FACTURE,
    AIA.SOURCE AS SOURCE
FROM 
    AP.AP_SUPPLIERS APS
    INNER JOIN AP.AP_INVOICES_ALL AIA 
        ON APS.VENDOR_ID = AIA.VENDOR_ID
    LEFT OUTER JOIN AP.AP_SUPPLIER_SITES_ALL APSA 
        ON AIA.VENDOR_SITE_ID = APSA.VENDOR_SITE_ID
    LEFT OUTER JOIN HR.HR_OPERATING_UNITS HOU 
        ON AIA.ORG_ID = HOU.ORGANIZATION_ID
WHERE 
    UPPER(APS.VENDOR_NAME) LIKE '%LA CRAU ENERGIES VERTES%'
    AND AIA.INVOICE_DATE >= TO_DATE('01/01/2025', 'DD/MM/YYYY')
ORDER BY 
    AIA.INVOICE_DATE DESC,
    AIA.INVOICE_NUM;

-- =====================================================================
-- PARTIE 6 : Statistiques des factures par Operating Unit
-- =====================================================================
SELECT 
    APS.VENDOR_NAME,
    HOU.NAME AS OPERATING_UNIT,
    EXTRACT(YEAR FROM AIA.INVOICE_DATE) AS ANNEE,
    EXTRACT(MONTH FROM AIA.INVOICE_DATE) AS MOIS,
    COUNT(*) AS NOMBRE_FACTURES,
    SUM(AIA.INVOICE_AMOUNT) AS TOTAL_FACTURES,
    SUM(CASE WHEN AIA.PAYMENT_STATUS_FLAG = 'Y' THEN AIA.INVOICE_AMOUNT ELSE 0 END) AS TOTAL_PAYE,
    SUM(CASE WHEN AIA.PAYMENT_STATUS_FLAG = 'N' THEN AIA.INVOICE_AMOUNT ELSE 0 END) AS TOTAL_IMPAYE,
    AIA.INVOICE_CURRENCY_CODE AS DEVISE
FROM 
    AP.AP_SUPPLIERS APS
    INNER JOIN AP.AP_INVOICES_ALL AIA 
        ON APS.VENDOR_ID = AIA.VENDOR_ID
    LEFT OUTER JOIN HR.HR_OPERATING_UNITS HOU 
        ON AIA.ORG_ID = HOU.ORGANIZATION_ID
WHERE 
    UPPER(APS.VENDOR_NAME) LIKE '%LA CRAU ENERGIES VERTES%'
    AND AIA.INVOICE_DATE >= TO_DATE('01/01/2025', 'DD/MM/YYYY')
    AND AIA.CANCELLED_DATE IS NULL
GROUP BY 
    APS.VENDOR_NAME,
    HOU.NAME,
    EXTRACT(YEAR FROM AIA.INVOICE_DATE),
    EXTRACT(MONTH FROM AIA.INVOICE_DATE),
    AIA.INVOICE_CURRENCY_CODE
ORDER BY 
    HOU.NAME,
    ANNEE DESC,
    MOIS DESC;

-- =====================================================================
-- PARTIE 7 : Bons de commande liés au fournisseur
-- =====================================================================
SELECT 
    APS.VENDOR_NAME,
    APS.SEGMENT1 AS NUMERO_FOURNISSEUR,
    HOU.NAME AS OPERATING_UNIT,
    PHA.SEGMENT1 AS NUMERO_BC,
    PHA.PO_HEADER_ID,
    PHA.TYPE_LOOKUP_CODE AS TYPE_BC,
    PHA.AUTHORIZATION_STATUS AS STATUT_AUTORISATION,
    PHA.APPROVED_FLAG AS APPROUVE,
    PHA.CLOSED_CODE AS CODE_FERMETURE,
    PHA.CANCEL_FLAG AS ANNULE,
    PHA.CREATION_DATE AS DATE_CREATION,
    PHA.APPROVED_DATE AS DATE_APPROBATION,
    PHA.CURRENCY_CODE AS DEVISE,
    (SELECT SUM(PLA.QUANTITY * PLA.UNIT_PRICE)
     FROM PO.PO_LINES_ALL PLA
     WHERE PLA.PO_HEADER_ID = PHA.PO_HEADER_ID) AS MONTANT_TOTAL_BC
FROM 
    AP.AP_SUPPLIERS APS
    INNER JOIN PO.PO_HEADERS_ALL PHA
        ON APS.VENDOR_ID = PHA.VENDOR_ID
    LEFT OUTER JOIN HR.HR_OPERATING_UNITS HOU 
        ON PHA.ORG_ID = HOU.ORGANIZATION_ID
WHERE 
    UPPER(APS.VENDOR_NAME) LIKE '%LA CRAU ENERGIES VERTES%'
ORDER BY 
    PHA.CREATION_DATE DESC;

-- =====================================================================
-- PARTIE 8 : Responsabilités AP/PO pour les Operating Units du fournisseur
-- =====================================================================
-- Cette requête liste les responsabilités liées aux modules AP (Accounts Payable)
-- et PO (Purchase Orders) pour les Operating Units où le fournisseur est référencé
SELECT DISTINCT
    HOU.NAME AS OPERATING_UNIT,
    HOU.ORGANIZATION_ID AS ORG_ID,
    FR.RESPONSIBILITY_NAME AS RESPONSABILITE,
    FR.RESPONSIBILITY_KEY AS CLE_RESPONSABILITE,
    FA.APPLICATION_NAME AS MODULE,
    FR.START_DATE AS DATE_DEBUT,
    FR.END_DATE AS DATE_FIN
FROM 
    AP.AP_SUPPLIERS APS
    INNER JOIN AP.AP_SUPPLIER_SITES_ALL APSA 
        ON APS.VENDOR_ID = APSA.VENDOR_ID
    INNER JOIN HR.HR_OPERATING_UNITS HOU 
        ON APSA.ORG_ID = HOU.ORGANIZATION_ID
    CROSS JOIN FND_RESPONSIBILITY_VL FR
    INNER JOIN FND_APPLICATION_VL FA
        ON FR.APPLICATION_ID = FA.APPLICATION_ID
WHERE 
    UPPER(APS.VENDOR_NAME) LIKE '%LA CRAU ENERGIES VERTES%'
    AND FA.APPLICATION_SHORT_NAME IN ('PO', 'AP', 'SQLAP')
    AND (HOU.SHORT_CODE IS NULL 
         OR UPPER(FR.RESPONSIBILITY_NAME) LIKE '%' || UPPER(TRIM(TO_CHAR(HOU.SHORT_CODE))) || '%')
    AND (FR.END_DATE IS NULL OR FR.END_DATE > SYSDATE)
ORDER BY 
    HOU.NAME,
    FA.APPLICATION_NAME,
    FR.RESPONSIBILITY_NAME;

-- =====================================================================
-- PARTIE 9 : Utilisateurs ayant accès aux responsabilités AP/PO 
--           pour les Operating Units du fournisseur
-- =====================================================================
SELECT DISTINCT
    HOU.NAME AS OPERATING_UNIT,
    FU.USER_NAME AS MATRICULE,
    FU.DESCRIPTION AS NOM_UTILISATEUR,
    FU.EMAIL_ADDRESS AS EMAIL_UTILISATEUR,
    FR.RESPONSIBILITY_NAME AS RESPONSABILITE,
    FA.APPLICATION_NAME AS MODULE,
    FURG.START_DATE AS DATE_DEBUT_AFFECTATION,
    FURG.END_DATE AS DATE_FIN_AFFECTATION
FROM 
    AP.AP_SUPPLIERS APS
    INNER JOIN AP.AP_SUPPLIER_SITES_ALL APSA 
        ON APS.VENDOR_ID = APSA.VENDOR_ID
    INNER JOIN HR.HR_OPERATING_UNITS HOU 
        ON APSA.ORG_ID = HOU.ORGANIZATION_ID
    CROSS JOIN FND_RESPONSIBILITY_VL FR
    INNER JOIN FND_APPLICATION_VL FA
        ON FR.APPLICATION_ID = FA.APPLICATION_ID
    INNER JOIN FND_USER_RESP_GROUPS_DIRECT FURG
        ON FR.RESPONSIBILITY_ID = FURG.RESPONSIBILITY_ID
        AND FR.APPLICATION_ID = FURG.RESPONSIBILITY_APPLICATION_ID
    INNER JOIN FND_USER FU
        ON FURG.USER_ID = FU.USER_ID
WHERE 
    UPPER(APS.VENDOR_NAME) LIKE '%LA CRAU ENERGIES VERTES%'
    AND FA.APPLICATION_SHORT_NAME IN ('PO', 'AP', 'SQLAP')
    AND (HOU.SHORT_CODE IS NULL 
         OR UPPER(FR.RESPONSIBILITY_NAME) LIKE '%' || UPPER(TRIM(TO_CHAR(HOU.SHORT_CODE))) || '%')
    AND (FR.END_DATE IS NULL OR FR.END_DATE > SYSDATE)
    AND (FURG.END_DATE IS NULL OR FURG.END_DATE > SYSDATE)
    AND (FU.END_DATE IS NULL OR FU.END_DATE > SYSDATE)
ORDER BY 
    HOU.NAME,
    FU.USER_NAME,
    FA.APPLICATION_NAME,
    FR.RESPONSIBILITY_NAME;
