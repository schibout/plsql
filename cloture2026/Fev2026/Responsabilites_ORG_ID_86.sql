-- =====================================================================
-- Recherche des Responsabilités pour ORG_ID = 86
-- =====================================================================
-- Date de création : 04/03/2026
-- Base de données : Oracle EBS Production
--
-- OBJECTIF : Extraire toutes les responsabilités liées à l'org_id 86
-- =====================================================================

-- =====================================================================
-- PARTIE 1 : Informations sur l'Operating Unit (org_id = 86)
-- =====================================================================
SELECT 
    HOU.ORGANIZATION_ID AS ORG_ID,
    HOU.NAME AS OPERATING_UNIT,
    HOU.SHORT_CODE AS CODE_OU,
    HOU.DATE_FROM AS DATE_DEBUT,
    HOU.DATE_TO AS DATE_FIN,
    HOU.INTERNAL_EXTERNAL_FLAG AS TYPE_ORG,
    HOU.SET_OF_BOOKS_ID AS LEDGER_ID,
    GL.NAME AS LEDGER_NAME,
    GL.CURRENCY_CODE AS DEVISE
FROM 
    HR.HR_OPERATING_UNITS HOU
    LEFT JOIN GL.GL_LEDGERS GL 
        ON HOU.SET_OF_BOOKS_ID = GL.LEDGER_ID
WHERE 
    HOU.ORGANIZATION_ID = 86;

-- =====================================================================
-- PARTIE 2 : Toutes les responsabilités liées à l'org_id 86
-- =====================================================================
-- Recherche basée sur le code OU dans le nom de la responsabilité
SELECT 
    FR.RESPONSIBILITY_ID,
    FR.RESPONSIBILITY_KEY AS CLE_RESPONSABILITE,
    FR.RESPONSIBILITY_NAME AS NOM_RESPONSABILITE,
    FA.APPLICATION_NAME AS MODULE,
    FA.APPLICATION_SHORT_NAME AS CODE_MODULE,
    FR.DESCRIPTION AS DESCRIPTION,
    FR.START_DATE AS DATE_DEBUT,
    FR.END_DATE AS DATE_FIN,
    FR.MENU_ID,
    FR.VERSION AS VERSION,
    FR.WEB_HOST_NAME,
    FR.WEB_AGENT_NAME
FROM 
    HR.HR_OPERATING_UNITS HOU
    CROSS JOIN APPS.FND_RESPONSIBILITY_VL FR
    INNER JOIN APPS.FND_APPLICATION_VL FA
        ON FR.APPLICATION_ID = FA.APPLICATION_ID
WHERE 
    HOU.ORGANIZATION_ID = 86
    AND (
        FR.RESPONSIBILITY_NAME LIKE '%' || HOU.SHORT_CODE || '%'
        OR FR.RESPONSIBILITY_KEY LIKE '%' || HOU.SHORT_CODE || '%'
    )
    AND (FR.END_DATE IS NULL OR FR.END_DATE > SYSDATE)
ORDER BY 
    FA.APPLICATION_NAME,
    FR.RESPONSIBILITY_NAME;

